/**
 * Post-build step that adds the cron (`scheduled`) handler to the Cloudflare worker
 *
 * adapter-cloudflare writes the SvelteKit worker to the `main` path from wrangler.jsonc
 * and doesn't support custom worker handlers. After `vite build` this script moves the
 * generated worker next to `main` and replaces `main` with a small entry that re-exports
 * SvelteKit's handlers together with the `scheduled` handler from ./cron.js.
 * Wrangler bundles everything when deploying.
 *
 * Runs automatically via the `postbuild` script in package.json.
 */
import fs from "node:fs";
import path from "node:path";

/** Worker entry - must match `main` in wrangler.jsonc */
const WORKER_ENTRY = ".svelte-kit/cloudflare/worker.mjs";
/** New name for the worker generated by adapter-cloudflare */
const SVELTEKIT_WORKER = "sveltekit-worker.mjs";
/** Module exporting the `scheduled` handler */
const CRON_MODULE = "src/lib/cloudflare/cron.js";

const MARKER = "// Generated by src/lib/cloudflare/postbuild.js";

const dir = path.dirname(WORKER_ENTRY);

if (!fs.existsSync(WORKER_ENTRY)) {
    throw new Error(
        `❌ ${WORKER_ENTRY} not found - run "vite build" first and make sure "main" in wrangler.jsonc points to it`
    );
}

if (fs.readFileSync(WORKER_ENTRY, "utf-8").startsWith(MARKER)) {
    console.log("ℹ️ Cron handler already added to the worker, skipping");
} else {
    fs.renameSync(WORKER_ENTRY, path.join(dir, SVELTEKIT_WORKER));

    const cronImport = path
        .relative(dir, CRON_MODULE)
        .split(path.sep)
        .join(path.posix.sep);

    fs.writeFileSync(
        WORKER_ENTRY,
        `${MARKER} - do not edit
import worker from "./${SVELTEKIT_WORKER}";
import { scheduled } from "${cronImport}";

export default { ...worker, scheduled };
`
    );

    // Keep the worker files out of the publicly served static assets
    fs.appendFileSync(
        path.join(dir, ".assetsignore"),
        `\n${path.basename(WORKER_ENTRY)}\n${SVELTEKIT_WORKER}\n`
    );

    console.log(`✅ Cron handler added to ${WORKER_ENTRY}`);
}
